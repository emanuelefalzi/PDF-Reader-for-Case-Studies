import Foundation

/// Human-readable label of a block, for example "3.2": chapter = 1-based
/// index of the level-1 contents entry whose page span contains the block's
/// start page (0 if none), "." followed by the block's 1-based index within
/// that chapter (among the blocks whose start page falls in the same span, in
/// block order). Pure: no dependency on `AnalysisController`/MainActor, so it
/// can be tested directly.
enum BlockLabeling {
    static func humanLabel(blockId: String, blocks: [TextBlock], level1TocEntries: [TocEntry]) -> String {
        guard let block = blocks.first(where: { $0.id == blockId }) else { return "0.0" }
        let chapters = level1TocEntries.sorted { $0.page < $1.page }

        guard let chapterIndex = chapters.firstIndex(where: { pageRange(of: $0, in: chapters).contains(block.pageStart) }) else {
            // No chapter contains the block (SPEC: "0 if none"): the inner
            // index falls back to the whole list of blocks.
            let withinIndex = (blocks.firstIndex(where: { $0.id == blockId }) ?? 0) + 1
            return withPartSuffix("0.\(withinIndex)", block: block)
        }

        let range = pageRange(of: chapters[chapterIndex], in: chapters)
        let blocksInChapter = blocks.filter { range.contains($0.pageStart) }
        let withinIndex = (blocksInChapter.firstIndex(where: { $0.id == blockId }) ?? 0) + 1
        return withPartSuffix("\(chapterIndex + 1).\(withinIndex)", block: block)
    }

    /// "3.2 · part 2 of 3" when the block's section has been split into
    /// several parts (`TextBlock.partIndex`/`partCount`, `BlockSegmenter`);
    /// the label stays "3.2" unchanged (no migration) for a block that is
    /// already the whole section. The label is generated by the app and
    /// localized like the rest of the UI, not text written by Claude, so it
    /// never shows up in the wrong language next to an English PDF.
    private static func withPartSuffix(_ label: String, block: TextBlock) -> String {
        guard let partIndex = block.partIndex, let partCount = block.partCount, partCount > 1 else { return label }
        return "\(label) \u{b7} part \(partIndex) of \(partCount)"
    }

    private static func pageRange(of entry: TocEntry, in sortedChapters: [TocEntry]) -> ClosedRange<Int> {
        guard let index = sortedChapters.firstIndex(where: { $0.id == entry.id }) else { return entry.page ... entry.page }
        let end = index + 1 < sortedChapters.count ? sortedChapters[index + 1].page - 1 : Int.max
        return entry.page ... Swift.max(entry.page, end)
    }
}
