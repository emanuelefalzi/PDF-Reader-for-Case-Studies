import Foundation

/// A saved block that no longer reattached to a real block after a new
/// segmentation (SPEC §7.3 "Stable block id"): it stays in the analysis with
/// `status: orphan`; the model keeps it with its old page to show it there
/// (the interface arrives in M5).
struct OrphanBlock: Sendable, Equatable {
    var blockId: String
    var page: Int
}

extension DocumentStore {
    /// Updates the index, blocks and Exhibits after the pipeline has
    /// produced/redone the structure (SPEC §7.4, §8). It reattaches the saved
    /// analyses to the new blocks: first by id, then by `textHash` (SPEC
    /// §7.3); those that do not reattach become "orphans" and are returned
    /// with their old page.
    /// `usePositionalFallback`: `true` by default (the long-standing
    /// behavior: same division, different text). A change of GRANULARITY
    /// (`DocumentModel.applySummaryGranularity`) passes `false`: changing
    /// granularity DELIBERATELY changes how many blocks fall on a page
    /// (merging/splitting is the point), so "same block count per page" is
    /// not a reliable signal of "same block" here. Reattaching by position in
    /// that case risks silently attaching the analysis of ONE old paragraph
    /// to a much larger new chapter block, marking it "analyzed" when it
    /// really covers only a small part of its true content. With `false`,
    /// id/`textHash` remain the only reattachment (SPEC §7.3 to the letter):
    /// more honest, orphaned when it is not the same text.
    @discardableResult
    func updateStructure(
        fingerprint: String,
        toc: TocRecord,
        segmentationVersion: Int,
        blocks: [BlockRecord],
        exhibits: [ExhibitRecord],
        usePositionalFallback: Bool = true,
        requireExactSpanForIdMatch: Bool = false
    ) -> [OrphanBlock] {
        guard var current = pending[fingerprint] else { return [] }
        let previousBlocks = current.record.blocks
        let newIds = Set(blocks.map(\.id))
        let newIdByHash = Dictionary(blocks.map { ($0.textHash, $0.id) }, uniquingKeysWith: { first, _ in first })

        // `toc` arrives here recomputed from the evaluation of the built-in
        // outline of THIS session alone (DocumentModel.init), which does not
        // distinguish "no useful built-in outline" from "no outline" in the
        // persisted schema (`TocRecord.Source` has only native|generated): the
        // caller always labels that case as `native` with `entries: []`. Since
        // `attachStructureToStore` calls `updateStructure` on EVERY open (the
        // pipeline always reruns), a `toc` recomputed this way would
        // needlessly overwrite an outline already generated by Claude in an
        // earlier session, reverting it to "native, 0 entries": the bug
        // observed on real data (the Merck case, "Responding to the Wii?").
        // An already generated outline with entries therefore stays the source
        // of truth until a new `toc` that is itself `generated` arrives (the
        // first generation completed, or "Regenerate contents").
        // The same protection as above applies only to the AUTOMATIC layer of
        // the outline: manual entries (v2.3 §5.3, `origin == .manual`,
        // including removal tombstones) always stay, merged with the
        // automatic layer chosen here via `mergeManualToc`.
        let hasRealAutoEntries = current.record.toc.entries.contains { $0.origin != .manual }
        let autoSourceToc: TocRecord
        if current.record.toc.source == .generated, hasRealAutoEntries, toc.source != .generated {
            autoSourceToc = current.record.toc
        } else {
            autoSourceToc = toc
        }
        let resolvedToc = TocRecord(source: autoSourceToc.source, entries: mergeManualToc(currentEntries: current.record.toc.entries, incomingAuto: autoSourceToc.entries))

        let reattachment = Self.reattach(
            previousBlocks: previousBlocks, newBlocks: blocks, analysisBlocks: current.analysis.blocks,
            newIds: newIds, newIdByHash: newIdByHash, usePositionalFallback: usePositionalFallback,
            requireExactSpanForIdMatch: requireExactSpanForIdMatch
        )
        let orphans = reattachment.orphans

        current.record.toc = resolvedToc
        current.record.segmentationVersion = segmentationVersion
        current.record.blocks = blocks
        current.record.exhibits = exhibits
        current.record.updatedAt = Date()
        current.analysis.blocks = reattachment.reattached
        pending[fingerprint] = current

        scheduleRecordSave(fingerprint: fingerprint)
        scheduleAnalysisSave(fingerprint: fingerprint)
        scheduleMarkdownExport(fingerprint: fingerprint)
        return orphans
    }

    /// Pure result of the reattachment (extracted from `updateStructure` so
    /// it can also be reused by a PREVIEW that writes nothing: "N summaries
    /// will need redoing" before confirming a granularity change; the exact
    /// same id → textHash → position rule, never a second version that could
    /// drift out of alignment).
    struct ReattachmentResult: Sendable, Equatable {
        var reattached: [String: BlockAnalysis]
        var orphans: [OrphanBlock]
    }

    /// Pure: no Store access, only `Sendable` input data.
    /// `requireExactSpanForIdMatch`: see below.
    static func reattach(
        previousBlocks: [BlockRecord],
        newBlocks: [BlockRecord],
        analysisBlocks: [String: BlockAnalysis],
        usePositionalFallback: Bool = true,
        requireExactSpanForIdMatch: Bool = false
    ) -> ReattachmentResult {
        let newIds = Set(newBlocks.map(\.id))
        let newIdByHash = Dictionary(newBlocks.map { ($0.textHash, $0.id) }, uniquingKeysWith: { first, _ in first })
        return reattach(
            previousBlocks: previousBlocks, newBlocks: newBlocks, analysisBlocks: analysisBlocks,
            newIds: newIds, newIdByHash: newIdByHash, usePositionalFallback: usePositionalFallback,
            requireExactSpanForIdMatch: requireExactSpanForIdMatch
        )
    }

    private static func reattach(
        previousBlocks: [BlockRecord],
        newBlocks: [BlockRecord],
        analysisBlocks: [String: BlockAnalysis],
        newIds: Set<String>,
        newIdByHash: [String: String],
        usePositionalFallback: Bool = true,
        requireExactSpanForIdMatch: Bool = false
    ) -> ReattachmentResult {
        var orphans: [OrphanBlock] = []
        var reattached: [String: BlockAnalysis] = [:]
        let newIdByPosition = usePositionalFallback ? Self.positionalMatches(previous: previousBlocks, new: newBlocks) : [:]
        let newBlockById = Dictionary(uniqueKeysWithValues: newBlocks.map { ($0.id, $0) })
        let claimed = Set(analysisBlocks.keys).intersection(newIds)
        for (oldId, analysis) in analysisBlocks {
            // A block's stable id (SPEC §7.3) depends on section + the first
            // 60 characters of the clean text + STARTING PAGE, not on the
            // ending page nor on the whole content. Merging several blocks
            // into one (a change of GRANULARITY, never a "normal"
            // re-segmentation) therefore makes the merged block's id match,
            // by construction, the id of the FIRST absorbed block, even though
            // it now covers much more text: without this extra check, the
            // analysis of the first block alone would stay silently attached
            // to the merged block, marked "analyzed" when it really covers
            // only part of its true content, which is worse than an honest
            // orphan. `requireExactSpanForIdMatch` also demands the same
            // `pageEnd`: an id matching with a different span goes on to the
            // `textHash` check (which fails, the content is different) and
            // then honestly orphaned.
            let idMatchesBlock = newBlockById[oldId].map { !requireExactSpanForIdMatch || $0.pageEnd == previousBlocks.first(where: { $0.id == oldId })?.pageEnd } ?? false
            if newIds.contains(oldId), idMatchesBlock {
                reattached[oldId] = analysis
            } else if let oldBlock = previousBlocks.first(where: { $0.id == oldId }),
                      let newId = newIdByHash[oldBlock.textHash] {
                reattached[newId] = analysis
            } else if let newId = newIdByPosition[oldId], !claimed.contains(newId), reattached[newId] == nil {
                // The block's text changed (doubled letters removed) but the
                // division did not: same place on the same page, so it is
                // the same block.
                reattached[newId] = analysis
            } else {
                var orphaned = analysis
                orphaned.status = .orphan
                reattached[oldId] = orphaned
                let page = previousBlocks.first { $0.id == oldId }?.pageStart ?? 0
                orphans.append(OrphanBlock(blockId: oldId, page: page))
            }
        }
        return ReattachmentResult(reattached: reattached, orphans: orphans)
    }

    /// Fallback reattachment by position: if on a page the old and the new
    /// segmentation have the same number of blocks (by starting page), the
    /// i-th old block corresponds to the i-th new one. It is needed when only
    /// the extracted text changes (different id and `textHash`), not the
    /// division into blocks; if the counts differ it does not guess.
    static func positionalMatches(previous: [BlockRecord], new: [BlockRecord]) -> [String: String] {
        let oldByPage = Dictionary(grouping: previous, by: \.pageStart)
        let newByPage = Dictionary(grouping: new, by: \.pageStart)
        var result: [String: String] = [:]
        for (page, oldBlocks) in oldByPage {
            guard let newBlocks = newByPage[page], newBlocks.count == oldBlocks.count else { continue }
            for (old, new) in zip(oldBlocks, newBlocks) { result[old.id] = new.id }
        }
        return result
    }

    /// Last page read (SPEC §8 `progress.lastReadPage`, replaces the
    /// provisional `LastPageStore`).
    func updateProgress(fingerprint: String, lastReadPage: Int) {
        guard var current = pending[fingerprint], current.record.progress.lastReadPage != lastReadPage else { return }
        current.record.progress.lastReadPage = lastReadPage
        current.record.updatedAt = Date()
        pending[fingerprint] = current
        scheduleRecordSave(fingerprint: fingerprint)
    }

    /// API for M5/M7/M8: modifies `analisi.json` in memory, then schedules
    /// the write (debounce) and the Markdown export (2 s later).
    func updateAnalysis(fingerprint: String, _ mutate: @Sendable (inout AnalysisRecord) -> Void) {
        guard var current = pending[fingerprint] else { return }
        mutate(&current.analysis)
        pending[fingerprint] = current
        scheduleAnalysisSave(fingerprint: fingerprint)
        scheduleMarkdownExport(fingerprint: fingerprint)
    }

    /// Analysis progress (SPEC §8 `progress.analyzedBlockIds`/
    /// `lastAnalyzedBlockId`, M5a deliverable 3): to be called right after
    /// every successful analysis of a block, in addition to `updateAnalysis`
    /// (that touches only `analisi.json`, this one `documento.json`). It does
    /// not duplicate `blockId` if the block had already been analyzed in the
    /// past (targeted reanalysis/regeneration, SPEC §7.6).
    func markBlockAnalyzed(fingerprint: String, blockId: String) {
        guard var current = pending[fingerprint] else { return }
        if !current.record.progress.analyzedBlockIds.contains(blockId) {
            current.record.progress.analyzedBlockIds.append(blockId)
        }
        current.record.progress.lastAnalyzedBlockId = blockId
        current.record.updatedAt = Date()
        pending[fingerprint] = current
        scheduleRecordSave(fingerprint: fingerprint)
    }

    /// Subject color (SPEC §5.4 v2.6, §8 `colorTheme`): chosen from the
    /// sidebar legend for the open document. Like `updateProgress`: a no-op
    /// if the document is not yet registered or if the color has not really
    /// changed.
    func updateColorTheme(fingerprint: String, colorTheme: MaterialHue) {
        guard var current = pending[fingerprint], current.record.colorTheme != colorTheme else { return }
        current.record.colorTheme = colorTheme
        current.record.updatedAt = Date()
        pending[fingerprint] = current
        scheduleRecordSave(fingerprint: fingerprint)
    }

    /// Summary granularity chosen for the document: the same scheme as
    /// `updateColorTheme` above (a no-op if the document is not yet
    /// registered or if the value has not changed). Whoever calls this
    /// function has already recomputed/saved the blocks with `updateStructure`
    /// (SPEC §7.3): here only THE CHOICE is recorded, i.e. what must happen at
    /// the next open/regeneration of the contents, not the blocks themselves.
    func updateSummaryGranularity(fingerprint: String, granularity: SummaryGranularity) {
        guard var current = pending[fingerprint], current.record.summaryGranularity != granularity else { return }
        current.record.summaryGranularity = granularity
        current.record.updatedAt = Date()
        pending[fingerprint] = current
        scheduleRecordSave(fingerprint: fingerprint)
    }

    /// Ids of the collapsed contents entries (the state is remembered per
    /// document): the same scheme as `updateColorTheme` above (a comparison
    /// to avoid a no-op write).
    func updateCollapsedTocEntryIds(fingerprint: String, ids: Set<String>) {
        guard var current = pending[fingerprint] else { return }
        let sorted = ids.sorted()
        guard current.record.collapsedTocEntryIds != sorted else { return }
        current.record.collapsedTocEntryIds = sorted
        current.record.updatedAt = Date()
        pending[fingerprint] = current
        scheduleRecordSave(fingerprint: fingerprint)
    }

    /// Generated contents (SPEC §7.4, M4): replaces the automatic layer of
    /// `toc` without touching blocks/Exhibits. Used both at the first
    /// generation and by "Regenerate contents" (SPEC §5.3, v2.3: "keeps and
    /// replaces only the automatic ones"; M7-2, merged with the manual entries
    /// via `mergeManualToc`, the same rule as `updateStructure`).
    func updateToc(fingerprint: String, toc: TocRecord) {
        guard var current = pending[fingerprint] else { return }
        current.record.toc = TocRecord(source: toc.source, entries: mergeManualToc(currentEntries: current.record.toc.entries, incomingAuto: toc.entries))
        current.record.updatedAt = Date()
        pending[fingerprint] = current
        scheduleRecordSave(fingerprint: fingerprint)
        scheduleMarkdownExport(fingerprint: fingerprint)
    }

    /// Merges the manual entries already saved (added, changed or removal
    /// tombstones, v2.3 §5.3) with an incoming new automatic outline
    /// (re-evaluated native or generated): shared by `updateStructure`/
    /// `updateToc` so as not to duplicate the "Regenerate contents ... only
    /// the automatic ones" rule (M7-2).
    private func mergeManualToc(currentEntries: [TocEntryRecord], incomingAuto: [TocEntryRecord]) -> [TocEntryRecord] {
        let manual = currentEntries.filter { $0.origin == .manual }
        return ManualToc.merge(manual: manual, newAuto: incomingAuto)
    }

    /// Adding/changing the level of/renaming/removing a manual contents
    /// entry (v2.3 §5.3, M7): a generic mutator, like `updateAnalysis`, so
    /// `DocumentModel` decides the exact change.
    func updateTocEntries(fingerprint: String, _ mutate: @Sendable (inout [TocEntryRecord]) -> Void) {
        guard var current = pending[fingerprint] else { return }
        mutate(&current.record.toc.entries)
        current.record.updatedAt = Date()
        pending[fingerprint] = current
        scheduleRecordSave(fingerprint: fingerprint)
        scheduleMarkdownExport(fingerprint: fingerprint)
    }
}
